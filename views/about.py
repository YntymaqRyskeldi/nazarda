"""«Жоба туралы»: мақсаты, алгоритмдер, шектеулер, AI көмегі, демо деректерді қалпына келтіру."""
from __future__ import annotations

import streamlit as st

from demo import seed
from ui import kit


def render() -> None:
    kit.show_flash()
    st.title("Жоба туралы")
    st.html('<p class="nz-big" style="margin:0">NAZARDA</p><p class="nz-sub">Әр қадам назарда.</p>')
    st.write("NAZARDA — оқушыға күнін, оқуын, қалта ақшасын және мақсаттарын бір жерде жоспарлауға көмектесетін "
             "мектептік жоспарлаушы. Ата-ана мен мұғалім оқушыны бақылау үшін емес, қолдау үшін қатысады.")

    with st.container(border=True, key="card_about_modes"):
        kit.h("Жұмыс режимдері")
        st.markdown(
            "- **Демо режимі** (қазір қосулы): рөлді бүйірлік мәзірден еркін ауыстыруға болады. Бұл — қорғалған кіру "
            "емес, тек мүмкіндіктерді көрсету.\n"
            "- **Жеке аккаунттар**: бұл нұсқада қосылмаған. Қосу үшін OIDC провайдері (мысалы, Google немесе "
            "Microsoft) және `st.login` баптауы қажет — нұсқаулық README файлында. Сервис қабаты әр сұрауда "
            "құқықты тексереді, сондықтан нақты кіру қосылғанда тек пайдаланушыны анықтау бөлігі ауысады.")

    with st.container(border=True, key="card_about_alg"):
        kit.h("Есептеулер қалай жасалады")
        st.markdown(
            "- **Үлгілік есептеу:** Σ(балл ÷ ең жоғары балл × 100 × салмақ) ÷ Σ салмақ. Нөл балл да есепке кіреді. "
            "Бұл ресми тоқсандық баға емес.\n"
            "- **Ерте ескерту:** бір пәннің бір бағалау түріндегі соңғы 3 жұмысы қатарынан төмендесе және жалпы "
            "төмендеу шектен (әдепкі 10 пайыздық тармақ) кем болмаса. Себебін анықтамайды — тек назар аударады.\n"
            "- **Қаржы:** жалпы қалдық = кіріс − шығыс; қолжетімді = жалпы қалдық − мақсаттарға бөлінген. "
            "Мақсатқа бөлу шығыс емес. Ата-ананың уәдесі ақша берілгенше балансқа қосылмайды.\n"
            "- **Сатып алу жоспары:** қалған сома ÷ қалған апталар, теңгеге дейін жоғары дөңгелектенеді.")

    with st.container(border=True, key="card_about_limits"):
        kit.h("Шектеулер")
        st.markdown(
            "- Деректер пайдаланушылар енгізген мәліметтерге негізделеді; күнделік, банк немесе курс платформаларымен "
            "байланыс жоқ.\n"
            "- Хабарламалар мерзімді тексеру (polling) арқылы жаңарады, лезде жеткізілмейді.\n"
            "- Хабарландырулар тек қолданба ішінде; e-mail, SMS, push жіберілмейді.\n"
            "- SQLite бір серверге арналған; көп мектепке масштабтау үшін басқа дерекқор қажет.\n"
            "- Демо режимде кім болса да кез келген рөлді таңдай алады.")

    with st.container(border=True, key="card_about_ai"):
        kit.h("Жасанды интеллект көмегі туралы адал ескерту")
        st.write("Бұл бағдарламаның коды, құрылымы, демо деректері және мәтіндері Claude (Anthropic) жасанды "
                 "интеллект көмегімен техникалық тапсырма бойынша жасалды. Жоба авторы оны өз қолымен толық жазған "
                 "деп көрсетпеуі керек. Авторлық үлесті нақты сипаттаңыз: идея, талаптар, тестілеу, демонстрация, "
                 "өзгертулер.")

    with st.container(border=True, key="card_about_reset"):
        kit.h("Демо деректерді қалпына келтіру", "Барлық өзгерістер өшіп, бастапқы демо деректер қайта жасалады.")
        if st.button("Демо деректерді қалпына келтіру"):
            st.session_state["confirm_reset"] = True
        if st.session_state.get("confirm_reset"):
            st.warning("Демо дерекқордағы барлық өзгерістер жойылады. Растайсыз ба?")
            c1, c2 = st.columns(2)
            if c1.button("Иә, қалпына келтіру", type="primary"):
                seed.reset()
                keep = {}
                st.session_state.clear()
                st.session_state.update(keep)
                kit.flash("Демо деректер қалпына келтірілді.")
                st.rerun()
            if c2.button("Бас тарту"):
                st.session_state.pop("confirm_reset")
                st.rerun()
